export function serializeAvatarText(options) {
  const spec = createAvatarSpecification(options);
  const lines = [
    'AVATAR — TECHNICAL SPECIFICATION / FICHA TÉCNICA',
    `Schema: ${spec.schema}`, `Native configuration: ${spec.nativeConfig}`,
    `Model: ${spec.model}`, `Model SHA-256: ${spec.modelSha256}`, `Catalog SHA-256: ${spec.catalogSha256}`,
    ...(spec.createdAt ? [`Created at (UTC): ${spec.createdAt}`] : []),
    '', 'SELECTED OPTIONS / OPCIONES ELEGIDAS',
  ];
  for (const choice of spec.selections) {
    lines.push(`${choice.serializedIndex + 1}. ${choice.label}: ${choice.optionId} (option ${choice.optionIndex})`);
    if (choice.native.nodes) lines.push(`   Native node IDs: ${choice.native.nodes.length ? choice.native.nodes.join(', ') : '(none)'}`);
    if (choice.native.mats) lines.push(`   Materials: ${choice.native.mats.length ? choice.native.mats.join(', ') : '(none)'}`);
    for (const [name, color] of Object.entries(choice.colors || {})) lines.push(`   ${name}: ${color.hex} / ${color.value}`);
    for (const flag of ['layered', 'masked', 'squinted', 'tint']) if (Object.hasOwn(choice.native, flag)) lines.push(`   ${flag}: ${choice.native[flag]}`);
    if (choice.note) lines.push(`   Note: ${choice.note}`);
  }
  lines.push('', 'IMAGE / IMAGEN', `PNG: ${spec.image.width} × ${spec.image.height}`,
    `Framing: ${spec.image.framing}`, `Background: ${spec.image.background}`,
    `Background RGBA: ${spec.image.backgroundRgba.join(', ')}`,
    '', 'The twelve choices above reconstruct the avatar. Background and framing only affect the downloaded image.',
    'Las doce selecciones anteriores reconstruyen el avatar. El fondo y el encuadre sólo afectan a la imagen descargada.',
    '', beginMarker, JSON.stringify(spec, null, 2), endMarker, '');
  return lines.join('\n');
}

export function parseAvatarText(text) {
  if (typeof text !== 'string' || text.length > 100000) fail('Provide an avatar TXT specification.');
  const begin = text.indexOf(beginMarker), end = text.indexOf(endMarker);
  if (begin < 0 || end <= begin || text.indexOf(beginMarker, begin + beginMarker.length) >= 0 || text.indexOf(endMarker, end + endMarker.length) >= 0) {
    fail('The avatar JSON section is missing or ambiguous.');
  }
  let value;
  try { value = JSON.parse(text.slice(begin + beginMarker.length, end)); } catch { fail('The avatar JSON section is invalid.'); }
  if (!plainObject(value) || value.schema !== XOX_AVATAR_SOURCE.schema || value.catalogSha256 !== XOX_AVATAR_SOURCE.catalogSha256 || value.model !== XOX_AVATAR_SOURCE.model || value.modelSha256 !== XOX_AVATAR_SOURCE.modelSha256) {
    fail('This specification uses a different avatar model or catalog.');
  }
  if (!plainObject(value.image) || encodeAvatarConfig(value.configuration) !== value.nativeConfig) fail('Avatar selections do not match the native configuration.');
  const canonical = createAvatarSpecification({ avatar: value.nativeConfig, background: value.image.background, framing: value.image.framing, createdAt: value.createdAt });
  if (JSON.stringify(value.selections) !== JSON.stringify(canonical.selections) || JSON.stringify(value.image) !== JSON.stringify(canonical.image)) {
    fail('Avatar metadata does not match the selected options.');
  }
  return canonical;
}
